"""Draws the 64x64 RGBA gem sprite and embeds the PNG file as a byte array in asset.hpp.

Run:  uv run --no-project --with pillow python make_asset.py
Deterministic: no randomness, fixed compression settings. Writes asset.png (for looking at) and asset.hpp.

The sprite is made to make scaling visible: hard pixel edges, a 1 px checker pattern, a 1 px outline,
and a smooth teal glow whose alpha fades from 90 to 0 (semi-transparent pixels).
"""
from pathlib import Path

from PIL import Image, ImageDraw

SIZE = 64
TEAL = (13, 148, 136)
TEAL_DARK = (15, 118, 110)
ORANGE = (234, 88, 12)
INK = (17, 24, 39)

# Crown facets above the girdle (y = 26), pavilion facets below it, each with a light and a dark tone.
FACETS = [
    ([(4, 26), (20, 10), (32, 26)], (94, 234, 212), (20, 184, 166)),
    ([(20, 10), (44, 10), (32, 26)], (204, 251, 241), (94, 234, 212)),
    ([(44, 10), (60, 26), (32, 26)], (45, 212, 191), (13, 148, 136)),
    ([(4, 26), (22, 26), (32, 60)], (20, 184, 166), (15, 118, 110)),
    ([(22, 26), (42, 26), (32, 60)], (45, 212, 191), (13, 148, 136)),
    ([(42, 26), (60, 26), (32, 60)], (15, 118, 110), (19, 78, 74)),
]
CHECKER_FACET = 1  # the bright table facet gets a 1 px checker on top of its gradient


def lerp(a, b, t):
    return tuple(round(a[i] + (b[i] - a[i]) * t) for i in range(3))


def main():
    img = Image.new("RGBA", (SIZE, SIZE), TEAL + (0,))
    px = img.load()

    # Glow: alpha falls off smoothly with the distance to the center. RGB stays teal everywhere,
    # also where alpha is 0, so linear filtering does not pull in a dark fringe.
    for y in range(SIZE):
        for x in range(SIZE):
            d = ((x - 31.5) ** 2 + (y - 33.0) ** 2) ** 0.5
            t = max(0.0, 1.0 - d / 31.5)
            px[x, y] = TEAL + (round(90 * t * t),)

    # Facets: vertical gradient from the light to the dark tone inside each facet's bounding box.
    for index, (poly, light, dark) in enumerate(FACETS):
        mask = Image.new("L", (SIZE, SIZE), 0)
        ImageDraw.Draw(mask).polygon(poly, fill=255)
        ys = [p[1] for p in poly]
        top, bottom = min(ys), max(ys)
        for y in range(SIZE):
            for x in range(SIZE):
                if mask.getpixel((x, y)) == 0:
                    continue
                t = (y - top) / max(1, bottom - top)
                color = lerp(light, dark, t)
                if index == CHECKER_FACET and (x + y) % 2 == 0 and y > 12:
                    color = lerp(color, (255, 255, 255), 0.45)
                px[x, y] = color + (255,)

    draw = ImageDraw.Draw(img)
    # Inner edges in a dark teal, the silhouette in ink.
    for poly, _, _ in FACETS:
        draw.line(poly + [poly[0]], fill=TEAL_DARK + (255,), width=1)
    outline = [(32, 60), (4, 26), (20, 10), (44, 10), (60, 26)]
    draw.line(outline + [outline[0]], fill=INK + (255,), width=1)

    # Orange girdle stripe with a darker line below it.
    for x in range(5, 60):
        px[x, 26] = ORANGE + (255,)
        px[x, 27] = (180, 60, 8, 255)

    # A sharp highlight on the table and two sparkles.
    for x in range(22, 31):
        px[x, 11] = (255, 255, 255, 255)
    for cx, cy in ((53, 8), (9, 14)):
        for k in (-2, -1, 1, 2):
            px[cx + k, cy] = ORANGE + (255,)
            px[cx, cy + k] = ORANGE + (255,)
        px[cx, cy] = (255, 255, 255, 255)

    here = Path(__file__).parent
    img.save(here / "asset.png", format="PNG", optimize=False, compress_level=9)
    data = (here / "asset.png").read_bytes()

    lines = []
    for i in range(0, len(data), 24):
        lines.append("    " + ",".join(str(b) for b in data[i : i + 24]) + ",")
    header = (
        "// Generated by make_asset.py (a 64x64 RGBA PNG, the file as it lies on disk). Do not edit.\n"
        "#pragma once\n"
        "namespace asset {\n"
        f"inline constexpr unsigned char kGemPng[] = {{\n" + "\n".join(lines) + "\n};\n"
        "}  // namespace asset\n"
    )
    (here / "asset.hpp").write_text(header)
    print(f"asset.png: {len(data)} bytes")


main()
