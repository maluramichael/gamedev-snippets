"""Builds common/font_atlas.hpp: JetBrains Mono (the font malura.de uses) as small bitmap atlases.

Usage: uv run --no-project --with pillow python tools/make_font_atlas.py <regular.ttf> <bold.ttf>

Each atlas is a PNG with white glyphs on transparent ground (tinted with SDL_SetTextureColorMod), 16 glyphs per
row, one cell per character of CHARSET in order. The PNG bytes are embedded in the header, so the demos need no
data files and no font library. JetBrains Mono is licensed under the SIL Open Font License 1.1.
"""
import io
import math
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

CHARSET = "".join(chr(c) for c in range(32, 127)) + "äöüÄÖÜß°·×±…§€"
SIZES = (16, 32)
COLUMNS = 16
OUT = Path(__file__).resolve().parent.parent / "common" / "font_atlas.hpp"


def atlas(ttf: str, size: int) -> tuple[bytes, int, int]:
    font = ImageFont.truetype(ttf, size)
    ascent, descent = font.getmetrics()
    cell_w = math.ceil(font.getlength("M"))
    cell_h = ascent + descent
    rows = math.ceil(len(CHARSET) / COLUMNS)
    image = Image.new("RGBA", (cell_w * COLUMNS, cell_h * rows), (255, 255, 255, 0))
    for index, char in enumerate(CHARSET):
        mask = Image.new("L", (cell_w, cell_h), 0)
        ImageDraw.Draw(mask).text((0, 0), char, font=font, fill=255)
        cell = Image.new("RGBA", (cell_w, cell_h), (255, 255, 255, 0))
        cell.putalpha(mask)
        image.paste(cell, ((index % COLUMNS) * cell_w, (index // COLUMNS) * cell_h))
    buffer = io.BytesIO()
    image.save(buffer, "PNG", optimize=True)
    return buffer.getvalue(), cell_w, cell_h


def array(name: str, data: bytes) -> str:
    body = ",".join(str(b) for b in data)
    return f"inline constexpr unsigned char {name}[] = {{{body}}};\n"


def main() -> None:
    regular, bold = sys.argv[1], sys.argv[2]
    escaped = CHARSET.replace("\\", "\\\\").replace('"', '\\"')
    lines = [
        "// Generated by tools/make_font_atlas.py. JetBrains Mono, SIL Open Font License 1.1. Do not edit.\n",
        "#pragma once\n",
        "namespace gd::font {\n",
        f'inline constexpr const char* kCharset = "{escaped}";\n',
        f"inline constexpr int kColumns = {COLUMNS};\n",
    ]
    for size in SIZES:
        for label, path in (("Regular", regular), ("Bold", bold)):
            data, cell_w, cell_h = atlas(path, size)
            lines.append(f"inline constexpr int k{label}{size}CellW = {cell_w};\n")
            lines.append(f"inline constexpr int k{label}{size}CellH = {cell_h};\n")
            lines.append(array(f"k{label}{size}Png", data))
    lines.append("}  // namespace gd::font\n")
    OUT.write_text("".join(lines), encoding="utf-8")
    print(f"{OUT} {OUT.stat().st_size // 1024} KB")


if __name__ == "__main__":
    main()
